"""Recorded-response provider: serves the JSON fixtures under
app/market/fixtures/ (generated by scripts/generate_market_fixtures.py).

This is the no-API-key path for development, tests and the Review 2 demo:
every value is deterministic and clearly labelled `recorded-sample`, so
nothing is presented as live market data. It also doubles as the
recorded-response test double the provider abstraction was designed around.
"""

from __future__ import annotations

import json
from datetime import date
from functools import lru_cache
from pathlib import Path

from app.market.providers.base import (
    FinancialDataProvider,
    Fundamentals,
    PriceBar,
    PriceSeries,
    ProviderError,
    Quote,
)

FIXTURE_DIR = Path(__file__).resolve().parent.parent / "fixtures"
SOURCE = "recorded-sample"


def _parse_date(value: str | None) -> date | None:
    return date.fromisoformat(value) if value else None


class RecordedProvider(FinancialDataProvider):
    """Loads fixture files once, then serves filtered views of them."""

    name = SOURCE

    def _dataset(self, symbol: str) -> dict:
        path = FIXTURE_DIR / f"{symbol.upper()}.json"
        if not path.exists():
            raise ProviderError(f"No recorded data for symbol '{symbol}'.")
        return _load(path)

    def list_symbols(self) -> list[dict]:
        symbols = []
        for path in sorted(FIXTURE_DIR.glob("*.json")):
            data = _load(path)
            bars = data["bars"]
            quote = data.get("quote") or {}
            price = quote.get("price") or bars[-1]["close"]
            prev = quote.get("previous_close") or (bars[-2]["close"] if len(bars) > 1 else price)
            change_pct = round((price / prev - 1.0) * 100.0, 2) if price and prev else 0.0
            symbols.append(
                {
                    "symbol": data["symbol"],
                    "name": data["name"],
                    "currency": data["currency"],
                    "sector": data["sector"],
                    "price": price,
                    "change_pct": change_pct,
                    "bars_from": bars[0]["date"],
                    "bars_to": bars[-1]["date"],
                    "bar_count": len(bars),
                }
            )
        return symbols

    def get_daily_prices(
        self, symbol: str, start: date | None = None, end: date | None = None
    ) -> PriceSeries:
        data = self._dataset(symbol)
        bars = [
            PriceBar(
                date=date.fromisoformat(b["date"]),
                open=b["open"],
                high=b["high"],
                low=b["low"],
                close=b["close"],
                volume=b["volume"],
            )
            for b in data["bars"]
        ]
        if start is not None:
            bars = [b for b in bars if b.date >= start]
        if end is not None:
            bars = [b for b in bars if b.date <= end]
        if not bars:
            raise ProviderError(
                f"No recorded bars for '{symbol}' in the requested window."
            )
        return PriceSeries(
            symbol=data["symbol"],
            currency=data["currency"],
            source=SOURCE,
            bars=bars,
        )

    def get_quote(self, symbol: str) -> Quote:
        data = self._dataset(symbol)
        quote = data["quote"]
        price = quote.get("price")
        prev = quote.get("previous_close")
        return Quote(
            symbol=data["symbol"],
            price=price,
            previous_close=prev,
            change_pct=(
                round((price / prev - 1.0) * 100.0, 2)
                if price and prev
                else None
            ),
            currency=data["currency"],
            as_of=_parse_date(quote.get("as_of")),
            source=SOURCE,
        )

    def get_fundamentals(self, symbol: str) -> Fundamentals:
        data = self._dataset(symbol)
        f = data["fundamentals"]
        return Fundamentals(
            symbol=data["symbol"],
            currency=data["currency"],
            source=SOURCE,
            as_of=_parse_date(f.get("as_of")),
            sector=data.get("sector"),
            name=data.get("name"),
            shares_outstanding=f["shares_outstanding"],
            eps_ttm=f["eps_ttm"],
            eps_growth_pct=f.get("eps_growth_pct"),
            book_value_per_share=f.get("book_value_per_share"),
            dividend_per_share=f.get("dividend_per_share"),
            revenue_ttm=f["revenue_ttm"],
            ebitda_ttm=f["ebitda_ttm"],
            net_debt=f["net_debt"],
            free_cash_flow_ttm=f["free_cash_flow_ttm"],
            roe_pct=f.get("roe_pct"),
        )


@lru_cache(maxsize=None)
def _load(path: Path) -> dict:
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)
